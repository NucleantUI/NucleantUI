//
//  ClosureEquivalence.swift
//  NucleantUI
//
//  When two closures are the same view input: they run the same code over
//  equal captures.
//
//  A Swift closure is two words: the function it runs, and a context — a
//  heap object holding what it captured, or nothing when it captured
//  nothing. Two closures written at one spot share the function; what can
//  differ is the context. The runtime describes every closure context it
//  allocates: the context's metadata says where the captures start and
//  points at a capture descriptor that lists each captured value's type,
//  as a mangled name. The same on every platform the Swift runtime runs on.
//
//  So the captures are found, in order, at their types' sizes and
//  alignments, and each pair is compared as a view input is
//  (`_areEquivalent`): `==` for an `Equatable` value, identity for an
//  object, the source for a `Binding`, the bytes for plain data. A closure
//  that captured a changed value is then a changed input: the view holding
//  it is built again and runs the new closure, where keeping it would run
//  the old one over stale values.
//
//  What can't be read counts as changed, which only costs a rebuild: a
//  context whose descriptor needs generic metadata, a captured `var` (it
//  lives in a box of its own), a type the runtime can't resolve by name — a
//  captured closure among them, which the descriptor names by its lowered
//  type, and in an optimised build a type of the app's own that nothing
//  else needed metadata for.
//

/// Whether the closures two views hold in the stored property `name` run
/// the same code over equal captures. Generated by `@View` for each stored
/// closure; `field` says the property's type.
///
/// The closure is read where the view stores it, not handed over as a value:
/// passed as a generic value — a key path's value is one too — a closure is
/// wrapped in a thunk made there, a function of that place's own and a new
/// context holding the closure, and two wraps of one closure no longer look
/// alike. So the property's offset is looked up in the view type's own
/// metadata, by name, and the closure read from the struct as it was built.
@MainActor
public func _areEquivalentClosures<V, F>(_ a: V, _ b: V, _ field: KeyPath<V, F>, name: StaticString) -> Bool {
    guard isThickFunction(F.self), let offset = StoredFields.offset(of: name, in: V.self) else {
        // Thin and C functions are their address; anything else — a block,
        // an `@isolated(any)` function — has nothing to read it by.
        return _isPOD(F.self) && _plainBytesEqual(a[keyPath: field], b[keyPath: field])
    }
    return withUnsafeBytes(of: a) { a in
        withUnsafeBytes(of: b) { b in
            thickFunctionsAreEquivalent(a.baseAddress! + offset, b.baseAddress! + offset)
        }
    }
}

/// Where a struct stores each of its properties, read from its metadata:
/// the type descriptor lists the stored properties by name, in order, and
/// the metadata's field offset vector has their offsets in the same order.
@MainActor
private final class StoredFields {
    private struct Key: Hashable {
        let type: ObjectIdentifier
        let name: UnsafeRawPointer
    }

    /// By view type and the generated code's name literal.
    private static var offsets: [Key: Int?] = [:]

    static func offset(of name: StaticString, in type: Any.Type) -> Int? {
        let key = Key(type: ObjectIdentifier(type), name: UnsafeRawPointer(name.utf8Start))
        if let known = offsets[key] { return known }
        let offset = read(name, in: type)
        offsets[key] = .some(offset)
        return offset
    }

    /// The struct metadata: kind, then its type descriptor. The descriptor:
    /// flags, parent, name and access function (32 bits each), a relative
    /// pointer to its field descriptor, the number of fields, and where in
    /// the metadata (in words) the field offset vector starts. The field
    /// descriptor: two relative pointers, kind and record size (16 bits
    /// each), the number of records, then the records: flags, a relative
    /// pointer to the type's mangled name, a relative pointer to the name.
    private static func read(_ name: StaticString, in type: Any.Type) -> Int? {
        let metadata = unsafeBitCast(type, to: UnsafeRawPointer.self)
        guard metadata.load(as: UInt.self) == structKind else { return nil }
        let descriptor = metadata.load(fromByteOffset: wordSize, as: UnsafeRawPointer.self)
        let fieldsReference = descriptor + 16
        let relative = Int(fieldsReference.load(as: Int32.self))
        guard relative != 0 else { return nil }
        let fields = fieldsReference + relative
        let vector = Int(descriptor.load(fromByteOffset: 24, as: UInt32.self))
        let recordSize = Int(fields.load(fromByteOffset: 10, as: UInt16.self))
        let count = Int(fields.load(fromByteOffset: 12, as: UInt32.self))
        let wanted = UnsafeRawBufferPointer(start: name.utf8Start, count: name.utf8CodeUnitCount)
        for index in 0..<count {
            let nameReference = fields + 16 + index * recordSize + 8
            let fieldName = (nameReference + Int(nameReference.load(as: Int32.self)))
                .assumingMemoryBound(to: UInt8.self)
            guard matches(fieldName, wanted) else { continue }
            return Int(metadata.load(fromByteOffset: vector * wordSize + 4 * index, as: UInt32.self))
        }
        return nil
    }

    private static func matches(_ cString: UnsafePointer<UInt8>, _ wanted: UnsafeRawBufferPointer) -> Bool {
        for (index, byte) in wanted.enumerated() where cString[index] != byte {
            return false
        }
        return cString[wanted.count] == 0
    }
}

private let wordSize = MemoryLayout<UInt>.size

/// A heap object's header: its metadata and its reference counts — two
/// words on every platform (`HeapObject` in the runtime).
private let heapObjectHeaderSize = 2 * wordSize

/// Metadata kinds, as the runtime numbers them.
private let structKind: UInt = 0x200
private let optionalKind: UInt = 0x202
private let functionKind: UInt = 0x302
private let heapLocalVariableKind: UInt = 0x400

private func metadataKind(of type: Any.Type) -> UInt {
    unsafeBitCast(type, to: UnsafeRawPointer.self).load(as: UInt.self)
}

/// A Swift function — the function, then its context — or an optional one,
/// whose absence is a null function.
private func isThickFunction(_ type: Any.Type) -> Bool {
    func layout<T>(_: T.Type) -> (size: Int, isPOD: Bool) { (MemoryLayout<T>.size, _isPOD(T.self)) }
    let (size, isPOD) = _openExistential(type, do: layout)
    guard size == 2 * wordSize, !isPOD else { return false }
    switch metadataKind(of: type) {
    case functionKind:
        return true
    case optionalKind:
        // An enum's metadata: kind, descriptor, then its generic argument.
        let metadata = unsafeBitCast(type, to: UnsafeRawPointer.self)
        let wrapped = metadata.load(fromByteOffset: 2 * wordSize, as: UnsafeRawPointer.self)
        return wrapped.load(as: UInt.self) == functionKind
    default:
        return false
    }
}

/// Whether the two Swift functions stored at `a` and `b` are the same code
/// over equivalent captures.
@MainActor
private func thickFunctionsAreEquivalent(_ a: UnsafeRawPointer, _ b: UnsafeRawPointer) -> Bool {
    let function = a.load(as: UInt.self)
    guard function == b.load(as: UInt.self) else { return false }
    // Both absent: an absent optional function is a null function, and its
    // context word is not to be read.
    if function == 0 { return true }
    return contextsAreEquivalent(
        a.load(fromByteOffset: wordSize, as: UnsafeRawPointer?.self),
        b.load(fromByteOffset: wordSize, as: UnsafeRawPointer?.self)
    )
}

/// Whether two closure contexts hold equivalent captures.
@MainActor
private func contextsAreEquivalent(_ a: UnsafeRawPointer?, _ b: UnsafeRawPointer?) -> Bool {
    // The same context, or neither closure captured anything.
    if a == b { return true }
    guard let a, let b else { return false }
    let metadata = a.load(as: UnsafeRawPointer.self)
    guard metadata == b.load(as: UnsafeRawPointer.self) else { return false }
    // A context that is not a closure context of captures — a single
    // captured object standing in as the context itself, a captured `var`'s
    // box — is the same capture only as the same object, and it is not.
    guard let layout = CaptureLayout.of(metadata) else { return false }
    for capture in layout.captures {
        guard capture.isEquivalent(a + capture.offset, b + capture.offset) else { return false }
    }
    return true
}

/// Where each capture of one kind of closure context lives, and how to
/// compare it — worked out once per context metadata.
@MainActor
private struct CaptureLayout {
    struct Capture {
        let offset: Int
        let isEquivalent: @MainActor (UnsafeRawPointer, UnsafeRawPointer) -> Bool
    }

    let captures: [Capture]

    /// By context metadata; `nil` for a context that can't be read.
    private static var known: [UnsafeRawPointer: CaptureLayout?] = [:]

    static func of(_ metadata: UnsafeRawPointer) -> CaptureLayout? {
        if let layout = known[metadata] { return layout }
        let layout = read(metadata)
        known[metadata] = .some(layout)
        return layout
    }

    /// The context metadata: its kind; the offset of the first capture
    /// (32 bits); the capture descriptor. The descriptor: the number of
    /// capture types, of metadata sources and of generic bindings (32 bits
    /// each), then one relative pointer to a mangled type name per capture.
    /// The bindings come first in the context, a word each.
    ///
    /// A context whose layout is only known at run time — one holding a
    /// value of a type from a library built for evolution, a Foundation
    /// `Date` or a struct with one in it — records no offset (0): its
    /// captures start right after the object's header, two words on every
    /// platform, each at its own alignment, as the runtime lays them out.
    private static func read(_ metadata: UnsafeRawPointer) -> CaptureLayout? {
        guard metadata.load(as: UInt.self) == heapLocalVariableKind else { return nil }
        let recordedFirstCapture = Int(metadata.load(fromByteOffset: wordSize, as: UInt32.self))
        let firstCapture = recordedFirstCapture != 0 ? recordedFirstCapture : heapObjectHeaderSize
        guard let descriptor = metadata.load(fromByteOffset: 2 * wordSize, as: UnsafeRawPointer?.self) else {
            return nil
        }
        let count = Int(descriptor.load(as: UInt32.self))
        let metadataSources = descriptor.load(fromByteOffset: 4, as: UInt32.self)
        let bindings = Int(descriptor.load(fromByteOffset: 8, as: UInt32.self))
        // Generic captures are described against metadata the context
        // carries; their names don't resolve on their own.
        guard metadataSources == 0 else { return nil }

        var offset = firstCapture + bindings * wordSize
        var captures: [Capture] = []
        captures.reserveCapacity(count)
        for index in 0..<count {
            let record = descriptor + 12 + 4 * index
            let name = (record + Int(record.load(as: Int32.self))).assumingMemoryBound(to: UInt8.self)
            guard let type = _getTypeByMangledNameInContext(
                name,
                UInt(mangledNameLength(name)),
                genericContext: nil,
                genericArguments: nil
            ) else { return nil }
            let field = _openExistential(type, do: captureField)
            offset = (offset + field.alignment - 1) & ~(field.alignment - 1)
            captures.append(Capture(offset: offset, isEquivalent: field.isEquivalent))
            offset += field.size
        }
        return CaptureLayout(captures: captures)
    }
}

/// The size, alignment and comparison of a captured value of type `T`.
private nonisolated func captureField<T>(_: T.Type) -> (size: Int, alignment: Int, isEquivalent: @MainActor (UnsafeRawPointer, UnsafeRawPointer) -> Bool) {
    let isEquivalent: @MainActor (UnsafeRawPointer, UnsafeRawPointer) -> Bool
    if isThickFunction(T.self) {
        // A captured function, read in place as a stored one is.
        isEquivalent = { a, b in thickFunctionsAreEquivalent(a, b) }
    } else {
        isEquivalent = { a, b in
            _areEquivalent(a.assumingMemoryBound(to: T.self).pointee, b.assumingMemoryBound(to: T.self).pointee)
        }
    }
    return (MemoryLayout<T>.size, MemoryLayout<T>.alignment, isEquivalent)
}

/// The length of a mangled name that may hold symbolic references: a byte
/// 0x01–0x17 is followed by a 32-bit relative reference, a byte 0x18–0x1F
/// by a pointer, and either may contain zero bytes.
private func mangledNameLength(_ name: UnsafePointer<UInt8>) -> Int {
    var length = 0
    while true {
        switch name[length] {
        case 0:
            return length
        case 0x01...0x17:
            length += 1 + 4
        case 0x18...0x1F:
            length += 1 + wordSize
        default:
            length += 1
        }
    }
}
